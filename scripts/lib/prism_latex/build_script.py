#!/usr/bin/env python3
"""Write a reproducible build script that uses the local Prism project."""

from __future__ import annotations

import datetime as dt
import os
import shlex
import sys
import tempfile
from pathlib import Path
from typing import Sequence


SCRIPT_NAME = "prism-build.sh"
MANAGED_MARKER = "# Generated by Prism LaTeX. Manual edits may be replaced."
WORKFLOW_WRAPPERS = {
    "notes-latex": "latex-note.sh",
    "reviewer-latex": "latex-review.sh",
    "paper-latex": "latex-paper.sh",
}


def _identity(input_path: Path, project_dir: Path) -> str:
    return os.path.relpath(input_path, project_dir).replace("\r", "\\r").replace("\n", "\\n")


def _path_word(path: Path, project_dir: Path) -> str:
    relative = os.path.relpath(path, project_dir)
    return '"$SCRIPT_DIR"/' + shlex.quote(relative)


def _word(value: str) -> str:
    return shlex.quote(value)


def _render_script(
    workflow: str,
    input_path: Path,
    output_path: Path,
    project_dir: Path,
    options: Sequence[str],
) -> str:
    if workflow not in WORKFLOW_WRAPPERS:
        raise ValueError(f"Unsupported workflow: {workflow}")
    identity = _identity(input_path, project_dir)
    entrypoint = f"{workflow}/scripts/{workflow.replace('-', '_')}.py"
    wrapper = WORKFLOW_WRAPPERS[workflow]
    local_root = shlex.quote(str(Path(__file__).resolve().parents[3]))
    first_argument = '"$SCRIPT_DIR"' if workflow == "paper-latex" else _path_word(input_path, project_dir)
    command_words = ['"${RUNNER[@]}"', '"$ENTRYPOINT"', first_argument, "--out", _path_word(output_path, project_dir)]
    command_words.extend(_word(value) for value in options)
    command_words.append("--no-build-script")
    command = "\n".join(f"  {value}" for value in command_words)
    return f"""#!/usr/bin/env bash
set -Eeuo pipefail

{MANAGED_MARKER}
# prism-workflow: {workflow}
# prism-input: {identity}

SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
RECORDED_PROJECT_DIR={local_root}
WRAPPER_NAME={shlex.quote(wrapper)}

is_prism_project() {{
  [[ -f "$1/scripts/$WRAPPER_NAME" && -f "$1/skills/{entrypoint}" ]]
}}

if [[ -n "${{PRISM_LATEX_SKILLS_DIR:-}}" ]]; then
  ENTRYPOINT="$PRISM_LATEX_SKILLS_DIR/{entrypoint}"
  RUNNER=(python3)
else
  PROJECT_DIR="${{PRISM_PROJECT_DIR:-}}"
  if [[ -n "$PROJECT_DIR" ]]; then
    if ! is_prism_project "$PROJECT_DIR"; then
      echo "PRISM_PROJECT_DIR does not contain the Prism workflow: $PROJECT_DIR" >&2
      exit 1
    fi
  else
    candidate="$SCRIPT_DIR"
    while :; do
      if is_prism_project "$candidate"; then
        PROJECT_DIR="$candidate"
        break
      fi
      [[ "$candidate" == / ]] && break
      candidate="$(dirname "$candidate")"
    done
    if [[ -z "$PROJECT_DIR" ]] && is_prism_project "$RECORDED_PROJECT_DIR"; then
      PROJECT_DIR="$RECORDED_PROJECT_DIR"
    fi
    if [[ -z "$PROJECT_DIR" ]]; then
      echo "Prism project not found. Set PRISM_PROJECT_DIR to the Prism repository." >&2
      exit 1
    fi
  fi
  ENTRYPOINT="$PROJECT_DIR/scripts/$WRAPPER_NAME"
  RUNNER=(bash)
fi

if [[ ! -f "$ENTRYPOINT" ]]; then
  echo "Prism LaTeX entrypoint not found: $ENTRYPOINT" >&2
  echo "Set PRISM_PROJECT_DIR or PRISM_LATEX_SKILLS_DIR to an existing local workflow." >&2
  exit 1
fi

command=(
{command}
)
exec "${{command[@]}}"
"""


def _matches(text: str, workflow: str, identity: str) -> bool:
    lines = text.splitlines()
    return all(
        marker in lines
        for marker in (
            MANAGED_MARKER,
            f"# prism-workflow: {workflow}",
            f"# prism-input: {identity}",
        )
    )


def _backup_path(path: Path) -> Path:
    timestamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%d-%H%M%S")
    candidate = path.with_name(f"{path.name}.backup-{timestamp}")
    counter = 1
    while candidate.exists():
        candidate = path.with_name(f"{path.name}.backup-{timestamp}-{counter}")
        counter += 1
    return candidate


def write_build_script(
    *,
    workflow: str,
    input_path: Path,
    output_path: Path,
    project_dir: Path,
    options: Sequence[str],
    force: bool = False,
) -> Path | None:
    project_dir = project_dir.resolve()
    input_path = input_path.resolve()
    output_path = output_path.resolve()
    destination = project_dir / SCRIPT_NAME
    identity = _identity(input_path, project_dir)

    if destination.exists():
        existing = destination.read_text(encoding="utf-8", errors="replace")
        if not _matches(existing, workflow, identity):
            if not force:
                print(
                    f"Warning: kept existing {destination}; use --force-build-script "
                    "to back it up and replace it.",
                    file=sys.stderr,
                )
                return None
            backup = _backup_path(destination)
            destination.replace(backup)
            print(f"Backed up build script: {backup}")

    content = _render_script(workflow, input_path, output_path, project_dir, options)
    fd, temporary = tempfile.mkstemp(
        prefix=f".{SCRIPT_NAME}.", suffix=".tmp", dir=project_dir
    )
    os.close(fd)
    temporary_path = Path(temporary)
    try:
        temporary_path.write_text(content, encoding="utf-8")
        temporary_path.chmod(0o755)
        os.replace(temporary_path, destination)
    finally:
        temporary_path.unlink(missing_ok=True)
    print(f"Wrote build script: {destination}")
    return destination
